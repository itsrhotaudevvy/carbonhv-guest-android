#!/usr/bin/env bash
# Repacks a published AOSP Cuttlefish image zip into the CarbonHV artifact layout.
#
#   ci/repack.sh <image.zip> <out-dir> [build-id]
#
# Nothing here compiles Android and nothing here runs as root. The output is:
#   <out-dir>/artifacts/…            one file per partition the image ships
#   <out-dir>/partitions.txt         role, file name, bytes, sha256 — the inventory, in order
#   <out-dir>/bundle.toml            a CarbonHV manifest whose zero development hashes are replaced
#                                    with the real ones (bundles/schema.md requires that)
#
# The bundle is labelled `android-standin`: a Google-built AOSP Cuttlefish image is not
# GrapheneOS, and the manifest says so in the only place that ships with the artifacts.
set -euo pipefail

image_zip="${1:?usage: repack.sh <image.zip> <out-dir> [build-id]}"
out="${2:?usage: repack.sh <image.zip> <out-dir> [build-id]}"
build_id="${3:-unknown}"
here="$(cd "$(dirname "$0")" && pwd)"

[[ -f "$image_zip" ]] || { echo "repack: no such image zip: $image_zip" >&2; exit 2; }

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

unzip -q "$image_zip" -d "$work"
mkdir -p "$out/artifacts"

# Roles follow the CarbonHV manifest vocabulary where it exists (boot, system) and otherwise name
# the partition, so the inventory is self-describing.
declare -A role_for=(
  [boot.img]=boot
  [system.img]=system
  [super.img]=super
  [init_boot.img]=init_boot
  [vendor_boot.img]=vendor_boot
  [userdata.img]=userdata
  [vbmeta.img]=vbmeta
  [vbmeta_system.img]=vbmeta_system
  [vendor.img]=vendor
  [kernel]=kernel
  [ramdisk.img]=ramdisk
)

inventory="$out/partitions.txt"
: >"$inventory"
artifacts_toml=""

# Stable order, so two runs of the same image produce the same manifest.
while IFS= read -r file; do
  name="$(basename "$file")"
  role="${role_for[$name]:-$(printf '%s' "$name" | sed 's/\.[^.]*$//; s/[^A-Za-z0-9_]/_/g')}"
  cp "$file" "$out/artifacts/$name"
  bytes="$(wc -c <"$out/artifacts/$name" | tr -d ' ')"
  digest="$(sha256sum "$out/artifacts/$name" | awk '{print $1}')"
  printf '%s\t%s\t%s\t%s\n' "$role" "$name" "$bytes" "$digest" >>"$inventory"
  artifacts_toml+="artifact = \"$role|artifacts/$name|$digest\""$'\n'
done < <(find "$work" -maxdepth 2 -type f \( -name '*.img' -o -name 'kernel' -o -name 'ramdisk.img' \) | sort)

if [[ ! -s "$inventory" ]]; then
  echo "repack: the image zip contained no partition images; refusing to publish an empty bundle" >&2
  echo "repack: contents were:" >&2
  find "$work" -maxdepth 2 -type f -printf '  %P\n' >&2 || true
  exit 3
fi

cat >"$out/bundle.toml" <<TOML
# Generated by carbonhv-guest-android ci/repack.sh from an official AOSP Cuttlefish image.
# This is NOT GrapheneOS. It is the plan's sanctioned stand-in guest and must be labelled as such
# wherever it appears: no GrapheneOS feature claim, no supported-device claim, no attestation.
id = "android-standin"
display_name = "AOSP Cuttlefish stand-in guest (ARM64, not GrapheneOS)"
version = "${build_id}"
publisher = "AOSP CI (rebuilt by CarbonHV CI), not GrapheneOS"
release_status = "development"
guest_arch = "arm64"
cvd_major = 1
memory_mib = 4096
storage_mib = 24576
requires_hardware_virtualization = true
requires_gpu_acceleration = true
backend = "avf"
integration_profile = "private"
$artifacts_toml
TOML

echo "repack: $(wc -l <"$inventory" | tr -d ' ') partition(s), $(du -sh "$out/artifacts" | awk '{print $1}')"
echo "repack: manifest at $out/bundle.toml"
